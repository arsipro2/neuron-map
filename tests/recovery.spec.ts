import { test, expect } from '@playwright/test'
import { seed, point, fixture } from './helpers'

async function recovery(page: import('@playwright/test').Page) {
  await page.locator('.workspace-switcher').click()
  await page.getByRole('button', { name: 'Recovery & backups', exact: true }).click()
}

test('deleting a connector source cancels the gesture and undo restores normal selection', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await seed(page)
  const p = await point(page, 'alpha')
  await page.mouse.move(p.x, p.y); await page.waitForTimeout(200)
  await page.mouse.move(p.x + 44, p.y); await page.mouse.down(); await page.mouse.move(p.x + 130, p.y - 50, { steps: 5 })
  await page.keyboard.press('Delete'); await page.mouse.up()
  const b = await point(page, 'beta'); await page.mouse.click(b.x, b.y)
  await expect(page.locator('.title-input')).toHaveValue('Beta')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  const a = await point(page, 'alpha'); await page.mouse.click(a.x, a.y)
  await expect(page.locator('.title-input')).toHaveValue('Alpha')
  expect(errors).toEqual([])
})

test('trash and attached bytes survive restart and note restoration', async ({ page }) => {
  await seed(page)
  await page.getByLabel('Attach files', { exact: true }).setInputFiles({ name: 'keep.bin', mimeType: 'application/octet-stream', buffer: Buffer.from([1, 0, 255]) })
  await expect(page.locator('.attachment-row')).toHaveCount(1)
  await page.getByTitle('Move note to Trash').click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.save-indicator')).toHaveClass(/saved/)
  await page.reload(); await expect(page.locator('canvas')).toBeVisible()
  await recovery(page)
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(page.locator('.title-input')).toHaveValue('Alpha')
  const [download] = await Promise.all([page.waitForEvent('download'), page.locator('.attachment-name').click()])
  const stream = await download.createReadStream(), chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(chunk)
  expect(Buffer.concat(chunks)).toEqual(Buffer.from([1, 0, 255]))
})

test('oldest of twenty snapshots restores without losing current unsaved edits', async ({ page }) => {
  await seed(page)
  await page.evaluate(async () => {
    const { useGraphStore } = await import('/src/store/useGraphStore.ts')
    const { flushPersist } = await import('/src/services/persistence.ts')
    for (let i = 0; i < 20; i++) { useGraphStore.getState().updateNode('alpha', { content: `Version ${i}` }); await flushPersist({ createBackup: true }) }
    useGraphStore.getState().updateNode('alpha', { content: 'Unsaved safety copy' })
  })
  page.on('dialog', d => d.accept())
  await recovery(page); await page.getByRole('tab', { name: 'Snapshots', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Restore snapshot', exact: true })).toHaveCount(20)
  await page.getByRole('button', { name: 'Restore snapshot', exact: true }).last().click()
  await expect(page.locator('.content-input')).toHaveValue('Version 0')
  await recovery(page); await page.getByRole('tab', { name: 'Snapshots', exact: true }).click()
  await page.getByRole('button', { name: 'Restore snapshot', exact: true }).first().click()
  await expect(page.locator('.content-input')).toHaveValue('Unsaved safety copy')
})

test('backup copy exports current memory after a failed save', async ({ page }) => {
  await seed(page)
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function(key, value) { if (key.startsWith('neuron-map-workspace-')) throw new DOMException('Disk full', 'QuotaExceededError'); original.call(this, key, value) }
  })
  await page.locator('.content-input').fill('Rescue these edits')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Retry', exact: true })).toBeVisible()
  page.on('dialog', d => d.accept())
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Save backup copy…', exact: true }).click()])
  const stream = await download.createReadStream(), chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(chunk)
  const payload = JSON.parse(Buffer.concat(chunks).toString())
  expect(payload.version).toBe(3); expect(payload.state.nodes[0].content).toBe('Rescue these edits')
  await expect(page.locator('.save-indicator')).toHaveClass(/error/)
})

