test('a stale browser tab reports a conflict instead of overwriting new edits', async ({ page, context }) => {
  await seed(page)
  const other = await context.newPage()
  await other.goto('/'); await expect(other.locator('.title-input')).toHaveValue('Alpha')
  await page.locator('.content-input').fill('Saved by the first tab')
  await page.getByRole('button', { name: 'Save', exact: true }).click(); await expect(page.locator('.save-indicator')).toHaveClass(/saved/)
  await other.locator('.content-input').fill('Stale second tab edit')
  await other.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(other.locator('.workspace-error-banner')).toContainText('SAVE_CONFLICT')
  const content = await page.evaluate(() => JSON.parse(localStorage.getItem('neuron-map-workspace-web-default')!).nodes[0].content)
  expect(content).toBe('Saved by the first tab')
  await other.close()
})
