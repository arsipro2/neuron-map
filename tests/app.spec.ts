test('large graph remains selectable offline; dropped/cancelled connector does not add a note', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message))
  const externalRequests: string[] = []
  await page.route('**/*', (route) => {
    const url = route.request().url()
    if (/^https?:/.test(url) && !url.startsWith('http://127.0.0.1:5183')) { externalRequests.push(url); return route.abort() }
    return route.continue()
  })
  const nodes = Array.from({ length: 1200 }, (_, i) => ({ id: `n${i}`, title: `Узел ${i}`, summary: 'Проверка кириллицы', content: `Содержимое ${i}`, position: [(i % 40 - 20) * 2, (Math.floor(i / 40) - 15) * 2, 0] }))
  const edges = nodes.slice(1).map((_, i) => ({ id: `e${i}`, source: `n${i}`, target: `n${i + 1}` }))
  for (let i = 0; i < 600; i++) edges.push({ id: `cross${i}`, source: `n${i}`, target: `n${i + 600}` })
  await page.addInitScript((state) => localStorage.setItem('neuron-map-workspace-web-default', JSON.stringify(state)), { ...fixture, nodes, edges, camera: { position: [0, 0, 30], quaternion: [0, 0, 0, 1], orbitTarget: [0, 0, 0] } })
  await page.goto('/'); await expect(page.locator('.top-stats')).toContainText('1200 notes')
  await page.waitForFunction(async () => { const { graphEngine } = await import('/src/engine/graphEngine.ts'); return graphEngine.runtime.ids.length === 1200 })
  const p = await point(page, 'n620')
  await page.mouse.click(p.x, p.y)
  await expect(page.locator('.content-input')).toHaveValue('Содержимое 620')
  await page.mouse.move(p.x, p.y); await page.waitForTimeout(250)
  await page.mouse.move(p.x + 44, p.y); await page.mouse.down(); await page.mouse.move(1300, p.y, { steps: 15 }); await page.mouse.up()
  await expect(page.locator('.top-stats')).toContainText('1200 notes')
  expect(errors).toEqual([])
  expect(externalRequests).toEqual([])
})
